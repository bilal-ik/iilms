function getBotReply(message) {
  const lower = message.toLowerCase();
  for (const rule of BOT_RULES) {
    if (rule.patterns.some(p => lower.includes(p))) {
      return rule.reply;
    }
  }
  return "🤔 I'm not sure about that. Try asking about:\n• **Internships** — how to find and apply\n• **Applications** — tracking your status\n• **Profile** — updating your information\n• **Complaints** — submitting issues\n\nOr contact your university admin for specific help.";
}

async function chat(req, res, next) {
  try {
    const { message, session_id } = req.body;
    if (!message || !session_id) {
      return res.status(400).json({ success: false, message: 'message and session_id are required' });
    }

    const user_id = req.user?.id || null;
    const reply = getBotReply(message);

    // Save both messages to DB
    await pool.query(
      'INSERT INTO ChatMessages (user_id, session_id, sender, message) VALUES (?, ?, ?, ?)',
      [user_id, session_id, 'user', message]
    );
    await pool.query(
      'INSERT INTO ChatMessages (user_id, session_id, sender, message) VALUES (?, ?, ?, ?)',
      [user_id, session_id, 'bot', reply]
    );

    return res.json({ success: true, data: { reply } });
  } catch (err) { next(err); }
}

async function getChatHistory(req, res, next) {
  try {
    const { session_id } = req.params;
    const [rows] = await pool.query(
      'SELECT sender, message, created_at FROM ChatMessages WHERE session_id = ? ORDER BY created_at ASC',
      [session_id]
    );
    return res.json({ success: true, data: rows });
  } catch (err) { next(err); }
}

module.exports = { chat, getChatHistory };
